#!/usr/bin/env python3
"""Generate neutral tentative method-return metadata from the pinned PHP oracle.

The class name inventory is the shared contract exporter, not a hand-maintained
SPL allowlist. Unknown methods remain strict. Regenerate the symbol registry
before this command when the neutral class catalog changes.
"""
import argparse
import json
from pathlib import Path
import subprocess

PIN = '34308a6666b2d489c509541ea9befea9e2b42348'


def main():
    """Verify the oracle and generate sorted keys for catalogued PHP class-like owners."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--php-src', type=Path, required=True)
    parser.add_argument('--php', default='php')
    args = parser.parse_args()
    head = subprocess.check_output(['git', '-C', str(args.php_src), 'rev-parse', 'HEAD'], text=True).strip()
    if head != PIN:
        parser.error('php-src must be pinned to ' + PIN)
    code = r'''
if (PHP_VERSION !== '8.5.10') { fwrite(STDERR, 'expected PHP 8.5.10'); exit(1); }
$out = [];
foreach (array_merge(get_declared_classes(), get_declared_interfaces()) as $class) {
    $rc = new ReflectionClass($class);
    if (!$rc->isInternal()) { continue; }
    foreach ($rc->getMethods() as $rm) {
        if ($rm->getDeclaringClass()->getName() === $class && $rm->hasTentativeReturnType()) {
            $out[] = [strtolower($class), strtolower($rm->getName()), (string)$rm->getTentativeReturnType()];
        }
    }
}
echo json_encode($out, JSON_THROW_ON_ERROR);
'''
    values = json.loads(subprocess.check_output([args.php, '-n', '-r', code], text=True))
    symbols = json.loads(Path('scripts/docs/symbol_registry.json').read_text())['classes']
    owners = {entry['name'].lower() for entry in symbols if not entry['internal']}
    values = sorted(tuple(row) for row in values if row[0] in owners)
    keys = [(owner, method) for owner, method, _ in values]
    if len(keys) != len(set(keys)):
        parser.error('duplicate method-return keys')
    header = '''//! Purpose:
//! Pinned tentative method-return contracts for catalogued PHP class-like owners.
//!
//! Called from:
//! - Compiler inheritance/interface validation for ReturnTypeWillChange.
//!
//! Key details:
//! - Generated by scripts/php_src/gen_tentative_method_returns.py; do not hand-edit the keys.
//! - php-src php-8.5.10, 34308a6666b2d489c509541ea9befea9e2b42348.
//! - An absent key is not permission to weaken a declared return contract.

/// Answers whether PHP marks this original declaring owner's method return as tentative.
pub fn method_return_is_tentative(owner: &str, method: &str) -> bool {
    let owner = owner.trim_start_matches('\\\\').to_ascii_lowercase();
    let method = method.to_ascii_lowercase();
    TENTATIVE_RETURNS.binary_search_by(|(class, name)| {
        (*class, *name).cmp(&(owner.as_str(), method.as_str()))
    }).is_ok()
}

/// Canonical original-owner/method pairs; inherited methods resolve their declaring owner first.
static TENTATIVE_RETURNS: &[(&str, &str)] = &[
'''
    lines = ['    (' + json.dumps(owner) + ', ' + json.dumps(method) + '),' for owner, method in keys]
    footer = '''
];

#[cfg(test)]
mod tests {
    use super::*;

    /// Tentative and mandatory SPL returns stay distinct, with canonical PHP symbol lookup.
    #[test]
    fn tentative_spl_returns_do_not_include_hard_contracts() {
        assert!(method_return_is_tentative("\\\\ArrayObject", "COUNT"));
        assert!(method_return_is_tentative("Countable", "count"));
        assert!(!method_return_is_tentative("SplObjectStorage", "seek"));
        assert!(!method_return_is_tentative("SplFixedArray", "getIterator"));
        assert!(!method_return_is_tentative("SplFixedArray", "jsonSerialize"));
        assert!(!method_return_is_tentative("UserClass", "count"));
    }

    /// Sorted unique keys and neutral class joins keep the generated lookup deterministic.
    #[test]
    fn tentative_return_keys_are_sorted_and_catalogued() {
        assert!(TENTATIVE_RETURNS.windows(2).all(|pair| pair[0] < pair[1]));
        for (owner, _) in TENTATIVE_RETURNS {
            assert!(crate::lookup_class(owner).is_some(), "{owner}");
        }
    }
}
'''
    path = Path('crates/elephc-builtin-contract/src/method_returns.rs')
    path.write_text(header + '\n'.join(lines) + footer)
    print('generated', len(keys), 'tentative return contracts')


if __name__ == '__main__':
    main()
